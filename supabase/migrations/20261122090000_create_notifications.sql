-- One notification for one person. Written only by the triggers and
-- functions of this migration; the app reads its own rows and marks them read.
create table public.notifications (
  id           uuid primary key default gen_random_uuid(),
  recipient_id uuid not null
               constraint notifications_recipient_id_fkey references public.profiles (id) on delete cascade,
  inbox        text not null
               constraint notifications_inbox_check check (inbox in ('player', 'club_owner')),
  type         text not null
               constraint notifications_type_check check (type in (
                 'join_request_received', 'join_request_approved', 'join_request_declined', 'removed_from_club',
                 'ownership_offered', 'ownership_accepted', 'ownership_rejected', 'ownership_withdrawn',
                 'challenge_received', 'challenge_accepted', 'challenge_declined',
                 'schedule_proposed', 'schedule_accepted', 'schedule_declined', 'match_rescheduled', 'match_cancelled',
                 'lineup_selected', 'lineup_changed', 'lineup_dropped',
                 'result_published', 'result_corrected', 'player_of_match',
                 'announcement')),
  -- Snapshots for the wording (D3): club / opponent / person names, dates.
  params       jsonb not null default '{}'::jsonb
               constraint notifications_params_check
               check (jsonb_typeof(params) = 'object' and octet_length(params::text) <= 2048),
  -- What it is about. club / match become NULL when they are deleted; the
  -- subject (request, offer, challenge, announcement) has no foreign key: the
  -- app shows "no longer available" when it is gone.
  club_id      uuid
               constraint notifications_club_id_fkey references public.clubs (id) on delete set null,
  match_id     uuid
               constraint notifications_match_id_fkey references public.matches (id) on delete set null,
  subject_id   uuid,
  -- The other person named in params.person_name. When their account is
  -- deleted this becomes NULL and the name is forgotten (D11, trigger below).
  person_id    uuid
               constraint notifications_person_id_fkey references public.profiles (id) on delete set null,
  -- One notification per event and person (idempotent fan-out).
  dedupe_key   text not null
               constraint notifications_dedupe_key_check check (char_length(dedupe_key) between 1 and 200),
  created_at   timestamptz not null default now(),
  read_at      timestamptz,
  constraint notifications_recipient_dedupe_key unique (recipient_id, dedupe_key)
);

create index notifications_inbox_page_idx on public.notifications (recipient_id, inbox, created_at desc, id desc);
create index notifications_unread_idx on public.notifications (recipient_id, inbox) where read_at is null;
create index notifications_created_at_idx on public.notifications (created_at);
create index notifications_club_id_idx on public.notifications (club_id) where club_id is not null;
create index notifications_match_id_idx on public.notifications (match_id) where match_id is not null;
create index notifications_person_id_idx on public.notifications (person_id) where person_id is not null;

comment on table public.notifications is
