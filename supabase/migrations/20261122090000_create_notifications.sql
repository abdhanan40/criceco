-- Adds one notification, once per (recipient, key). Nobody is told of their
-- own action, and a missing recipient is skipped.
create or replace function public.notification_add(
  p_recipient  uuid,
  p_inbox      text,
  p_type       text,
  p_key        text,
  p_params     jsonb,
  p_club_id    uuid default null,
  p_match_id   uuid default null,
  p_subject_id uuid default null,
  p_person_id  uuid default null
)
returns void
language plpgsql
volatile
security definer
set search_path = ''
as $$
begin
  if p_recipient is null or p_recipient = (select auth.uid()) then
    return;
  end if;
  insert into public.notifications (recipient_id, inbox, type, params, club_id, match_id, subject_id, person_id, dedupe_key)
  values (p_recipient, p_inbox, p_type, jsonb_strip_nulls(coalesce(p_params, '{}'::jsonb)),
          p_club_id, p_match_id, p_subject_id, p_person_id, p_key)
  on conflict (recipient_id, dedupe_key) do nothing;
end;
$$;

create or replace function public.notification_person_name(p_user_id uuid)
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select nullif(btrim(p.full_name), '') from public.profiles p where p.id = p_user_id;
$$;

-- A result from one club's side: won / lost / tied / no_result / abandoned.
create or replace function public.notification_result_for(p_outcome text, p_club_a_id uuid, p_club_id uuid)
returns text
language sql
immutable
set search_path = ''
as $$
  select case p_outcome
           when 'club_a_won' then case when p_club_id = p_club_a_id then 'won' else 'lost' end
           when 'club_b_won' then case when p_club_id = p_club_a_id then 'lost' else 'won' end
           when 'tie' then 'tied'
           else p_outcome
         end;
$$;

-- Tells every active selected player of both line-ups of [p_match].
create or replace function public.notification_lineup_fanout(
  p_match  public.matches,
  p_type   text,
  p_key    text,
  p_params jsonb
)
returns void
language plpgsql
volatile
security definer
set search_path = ''
as $$
begin
  perform public.notification_add(
            m.user_id, case when m.member_role = 'owner' then 'club_owner' else 'player' end, p_type, p_key,
            coalesce(p_params, '{}'::jsonb)
              || jsonb_build_object('club_name', own.name, 'opponent_name', opp.name, 'selection', lp.selection),
            lp.club_id, p_match.id)
     from public.match_lineup_players lp
     join public.club_members m on m.id = lp.member_id and m.status = 'active'
     join public.clubs own on own.id = lp.club_id
     join public.clubs opp
       on opp.id = case when lp.club_id = p_match.club_a_id then p_match.club_b_id else p_match.club_a_id end
    where lp.match_id = p_match.id;
end;
$$;

