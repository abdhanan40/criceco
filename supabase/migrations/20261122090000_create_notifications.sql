-- Marks the caller's own notifications read; returns how many changed.
-- Other people's ids and already-read ones are ignored.
create or replace function public.mark_notifications_read(p_ids uuid[])
returns integer
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_uid   uuid := auth.uid();
  v_count integer;
begin
  if v_uid is null then
    raise exception 'notification: not authenticated' using errcode = '42501';
  end if;
  if p_ids is null or cardinality(p_ids) = 0 then
    return 0;
  end if;
  if cardinality(p_ids) > 200 then
    raise exception 'notification: invalid' using errcode = '22023';
  end if;
  update public.notifications n set read_at = now()
   where n.id = any (p_ids) and n.recipient_id = v_uid and n.read_at is null;
  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

