-- Official results: a version becomes official (by the trusted scorer path).
create or replace function public.match_results_notify()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_match public.matches;
  v_type  text;
  v_key   text;
  v_pom   public.club_members;
begin
  if new.status <> 'confirmed' or old.status = 'confirmed' then
    return null;
  end if;
  select * into v_match from public.matches m where m.id = new.match_id;
  if not found then
    return null;
  end if;
  -- First official version: the match is still 'confirmed' here (it becomes
  -- 'completed' right after, in the same call). Later ones are corrections.
  v_type := case when new.corrects_version is not null or v_match.status = 'completed'
                 then 'result_corrected' else 'result_published' end;
  v_key := 'result:' || new.match_id || ':v' || new.version;

  -- Both owners (their own inbox) first, then the other active members.
  perform public.notification_add(
            c.owner_id, 'club_owner', v_type, v_key,
            jsonb_build_object('club_name', c.name, 'opponent_name', o.name, 'version', new.version,
                               'result', public.notification_result_for(new.outcome, v_match.club_a_id, c.id)),
            c.id, new.match_id)
     from public.clubs c
     join public.clubs o on o.id = case when c.id = v_match.club_a_id then v_match.club_b_id else v_match.club_a_id end
    where c.id in (v_match.club_a_id, v_match.club_b_id);
  perform public.notification_add(
            m.user_id, 'player', v_type, v_key,
            jsonb_build_object('club_name', c.name, 'opponent_name', o.name, 'version', new.version,
                               'result', public.notification_result_for(new.outcome, v_match.club_a_id, c.id)),
            c.id, new.match_id)
     from public.club_members m
     join public.clubs c on c.id = m.club_id
     join public.clubs o on o.id = case when c.id = v_match.club_a_id then v_match.club_b_id else v_match.club_a_id end
    where m.club_id in (v_match.club_a_id, v_match.club_b_id) and m.status = 'active' and m.member_role <> 'owner';

  if new.player_of_match_member_id is not null then
    select * into v_pom from public.club_members m where m.id = new.player_of_match_member_id;
    if found then
      -- Once per match and player: a correction keeping them tells nothing new.
      perform public.notification_add(
                v_pom.user_id, case when v_pom.member_role = 'owner' then 'club_owner' else 'player' end,
                'player_of_match', 'potm:' || new.match_id || ':' || v_pom.id,
                jsonb_build_object('club_name', c.name, 'opponent_name', o.name),
                v_pom.club_id, new.match_id)
         from public.clubs c
         join public.clubs o on o.id = case when c.id = v_match.club_a_id then v_match.club_b_id else v_match.club_a_id end
        where c.id = v_pom.club_id;
    end if;
  end if;
  return null;
end;
$$;

create trigger match_results_notify
  after update of status on public.match_results
  for each row execute function public.match_results_notify();

-- ---------------------------------------------------------------------------
-- 5. The inbox API (authenticated; own rows only; the last 90 days — D7)
-- ---------------------------------------------------------------------------
-- One page, newest first. Next page: pass the last row's created_at and id.
create or replace function public.my_notifications(
  p_inbox     text,
  p_before    timestamptz default null,
  p_before_id uuid default null,
  p_limit     integer default 30
)
returns table (
  notification_id uuid,
  type            text,
  params          jsonb,
  club_id         uuid,
  match_id        uuid,
  subject_id      uuid,
  created_at      timestamptz,
  read_at         timestamptz
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
begin
  if v_uid is null then
    raise exception 'notification: not authenticated' using errcode = '42501';
  end if;
  if p_inbox is null or p_inbox not in ('player', 'club_owner')
     or (p_before is null) <> (p_before_id is null)
     or p_limit is null or p_limit not between 1 and 100 then
    raise exception 'notification: invalid' using errcode = '22023';
  end if;
  return query
    select n.id, n.type, n.params, n.club_id, n.match_id, n.subject_id, n.created_at, n.read_at
      from public.notifications n
     where n.recipient_id = v_uid and n.inbox = p_inbox
       and n.created_at > now() - interval '90 days'
       and (p_before is null or (n.created_at, n.id) < (p_before, p_before_id))
     order by n.created_at desc, n.id desc
     limit p_limit;
end;
$$;

