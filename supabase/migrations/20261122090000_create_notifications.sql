--   D6  read state on the server, per notification;
--   D7  90 days: the read functions show the last 90 days (cleanup job: P6);
--   D10 club announcements are stored and delivered by the server;
--   D11 a deleted account's own notifications go with it; in other people's
--       its name is forgotten (the app shows "Deleted player");
--   P1-A a notification is part of its action: if writing it fails, the
--       action fails (nothing is swallowed);
--   P1-B line-up notices only for confirmed matches (line-ups can only be
--       saved then); a reschedule tells the selected players.
--   Nobody is ever notified of their own action.
--
-- Events (type → recipient, inbox):
--   join_request_received → club owner (club_owner)
--   join_request_approved / join_request_declined → applicant (player)
--   removed_from_club → the removed member, unless they removed themselves (player)
--   ownership_offered / ownership_withdrawn → the member offered the club (player)
--   ownership_rejected → the owner who offered (club_owner)
--   ownership_accepted → the previous owner, no longer an owner (player)
--   challenge_received → the challenged club's owner (club_owner)
--   challenge_accepted / challenge_declined → the challenger's owner (club_owner)
--   schedule_proposed → the other club's owner (club_owner)
--   schedule_accepted / schedule_declined → the proposer's owner (club_owner)
--   match_rescheduled → the selected players (player; club_owner if the owner is selected)
--   match_cancelled → the other club's owner and the selected players of both clubs
--   lineup_selected / lineup_changed / lineup_dropped → that player (once, when the save commits)
--   result_published / result_corrected → both owners (club_owner) and the
--       other active members of both clubs (player)
--   player_of_match → that player
--   announcement → the members in the audience, except the author (player)

