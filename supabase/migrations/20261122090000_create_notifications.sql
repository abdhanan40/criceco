-- Memberships: a request arrives; the owner decides it.
create or replace function public.join_requests_notify()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_club public.clubs;
begin
  select * into v_club from public.clubs c where c.id = new.club_id;
  if not found then
    return null;
  end if;
  if tg_op = 'INSERT' then
    if new.status = 'pending' then
      perform public.notification_add(
                v_club.owner_id, 'club_owner', 'join_request_received', 'join_request:' || new.id || ':received',
                jsonb_build_object('club_name', v_club.name, 'person_name', public.notification_person_name(new.user_id)),
                new.club_id, null, new.id, new.user_id);
    end if;
  elsif old.status = 'pending' and new.status in ('approved', 'rejected') then
    perform public.notification_add(
              new.user_id, 'player',
              case new.status when 'approved' then 'join_request_approved' else 'join_request_declined' end,
              'join_request:' || new.id || ':' || new.status,
              jsonb_build_object('club_name', v_club.name, 'role', new.assigned_role),
              new.club_id, null, new.id);
  end if;
  return null;
end;
$$;

create trigger join_requests_notify
  after insert or update of status on public.join_requests
  for each row execute function public.join_requests_notify();

-- Memberships: removed from a club (no reason is ever stored — D4).
create or replace function public.club_members_notify_removed()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if old.status = 'active' and new.status = 'removed' and new.removed_by is distinct from new.user_id then
    perform public.notification_add(
              new.user_id, 'player', 'removed_from_club',
              'member:' || new.id || ':removed:' || floor(extract(epoch from new.removed_at) * 1000000)::bigint,
              jsonb_build_object('club_name', (select c.name from public.clubs c where c.id = new.club_id)),
              new.club_id);
  end if;
  return null;
end;
$$;

create trigger club_members_notify_removed
  after update of status on public.club_members
  for each row execute function public.club_members_notify_removed();

-- Ownership transfer: offered; accepted / rejected / withdrawn (expired: no notice).
create or replace function public.club_ownership_transfers_notify()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_club_name text := (select c.name from public.clubs c where c.id = new.club_id);
begin
  if tg_op = 'INSERT' then
    if new.status = 'pending' then
      perform public.notification_add(
                new.to_user_id, 'player', 'ownership_offered', 'ownership:' || new.id || ':offered',
                jsonb_build_object('club_name', v_club_name, 'person_name', public.notification_person_name(new.from_user_id),
                                   'expires_at', new.expires_at),
                new.club_id, null, new.id, new.from_user_id);
    end if;
  elsif old.status = 'pending' then
    if new.status = 'accepted' then
      -- The previous owner is a member now (their club_owner role is gone).
      perform public.notification_add(
                new.from_user_id, 'player', 'ownership_accepted', 'ownership:' || new.id || ':accepted',
                jsonb_build_object('club_name', v_club_name, 'person_name', public.notification_person_name(new.to_user_id)),
                new.club_id, null, new.id, new.to_user_id);
    elsif new.status = 'rejected' then
      perform public.notification_add(
                new.from_user_id, 'club_owner', 'ownership_rejected', 'ownership:' || new.id || ':rejected',
                jsonb_build_object('club_name', v_club_name, 'person_name', public.notification_person_name(new.to_user_id)),
                new.club_id, null, new.id, new.to_user_id);
    elsif new.status = 'cancelled' then
      perform public.notification_add(
                new.to_user_id, 'player', 'ownership_withdrawn', 'ownership:' || new.id || ':cancelled',
                jsonb_build_object('club_name', v_club_name, 'person_name', public.notification_person_name(new.from_user_id)),
                new.club_id, null, new.id, new.from_user_id);
    end if;
  end if;
  return null;
end;
$$;

create trigger club_ownership_transfers_notify
  after insert or update of status on public.club_ownership_transfers
  for each row execute function public.club_ownership_transfers_notify();

-- Challenges: received; accepted / declined (expired: no notice).
create or replace function public.match_challenges_notify()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_from  public.clubs;
  v_to    public.clubs;
  v_terms jsonb := jsonb_build_object('format', new.format, 'custom_overs', new.custom_overs,
                                      'proposed_date', new.proposed_date, 'venue_name', new.venue_name);
begin
  select * into v_from from public.clubs c where c.id = new.from_club_id;
  select * into v_to from public.clubs c where c.id = new.to_club_id;
  if tg_op = 'INSERT' then
    if new.status = 'pending' then
      perform public.notification_add(
                v_to.owner_id, 'club_owner', 'challenge_received', 'challenge:' || new.id || ':received',
                v_terms || jsonb_build_object('opponent_name', v_from.name),
                new.to_club_id, null, new.id);
    end if;
  elsif old.status = 'pending' and new.status in ('accepted', 'declined') then
    perform public.notification_add(
              v_from.owner_id, 'club_owner',
              case new.status when 'accepted' then 'challenge_accepted' else 'challenge_declined' end,
              'challenge:' || new.id || ':' || new.status,
              v_terms || jsonb_build_object('opponent_name', v_to.name),
              new.from_club_id, new.match_id, new.id);
  end if;
  return null;
end;
$$;

create trigger match_challenges_notify
  after insert or update of status on public.match_challenges
  for each row execute function public.match_challenges_notify();

-- Matches: schedule proposed / accepted / declined, rescheduled, cancelled.
-- (Completion is told by the result.)
create or replace function public.matches_notify()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_a     public.clubs;
  v_b     public.clubs;
  v_club  uuid;  -- the club to tell (its owner)
  v_owner uuid;
  v_opp   text;  -- the other club's name, from v_club's side
begin
  select * into v_a from public.clubs c where c.id = new.club_a_id;
  select * into v_b from public.clubs c where c.id = new.club_b_id;

  if new.status = 'cancelled' and old.status <> 'cancelled' then
    v_club := case when new.cancelled_by_club_id = new.club_a_id then new.club_b_id else new.club_a_id end;
    v_owner := case when v_club = new.club_a_id then v_a.owner_id else v_b.owner_id end;
    v_opp := case when v_club = new.club_a_id then v_b.name else v_a.name end;
    -- The other owner first, so an owner who is also selected is told once.
    perform public.notification_add(
              v_owner, 'club_owner', 'match_cancelled', 'match:' || new.id || ':cancelled',
              jsonb_build_object('opponent_name', v_opp, 'starts_at', old.starts_at), v_club, new.id);
    perform public.notification_lineup_fanout(new, 'match_cancelled', 'match:' || new.id || ':cancelled',
                                              jsonb_build_object('starts_at', old.starts_at));
    return null;
  end if;

  if new.proposed_by_club_id is not null and new.proposal_version > old.proposal_version then
    -- A (new) proposal: the other club's owner answers it.
    v_club := case when new.proposed_by_club_id = new.club_a_id then new.club_b_id else new.club_a_id end;
    v_owner := case when v_club = new.club_a_id then v_a.owner_id else v_b.owner_id end;
    v_opp := case when v_club = new.club_a_id then v_b.name else v_a.name end;
    perform public.notification_add(
              v_owner, 'club_owner', 'schedule_proposed',
              'match:' || new.id || ':proposal:' || new.proposal_version || ':proposed',
              jsonb_build_object('opponent_name', v_opp, 'starts_at', new.proposed_starts_at,
                                 'venue_name', new.proposed_venue_name, 'city', new.proposed_city,
                                 'reschedule', new.status = 'confirmed'),
              v_club, new.id);
  elsif old.proposed_by_club_id is not null and new.proposed_by_club_id is null then
    -- The proposal was answered: back to the proposer.
    v_club := old.proposed_by_club_id;
    v_owner := case when v_club = new.club_a_id then v_a.owner_id else v_b.owner_id end;
    v_opp := case when v_club = new.club_a_id then v_b.name else v_a.name end;
    if new.status = 'confirmed'
       and (new.starts_at, new.venue_name, new.city)
           is not distinct from (old.proposed_starts_at, old.proposed_venue_name, old.proposed_city) then
      perform public.notification_add(
                v_owner, 'club_owner', 'schedule_accepted',
                'match:' || new.id || ':proposal:' || old.proposal_version || ':accepted',
                jsonb_build_object('opponent_name', v_opp, 'starts_at', new.starts_at, 'venue_name', new.venue_name,
                                   'city', new.city, 'reschedule', old.status = 'confirmed'),
                v_club, new.id);
      if old.status = 'confirmed' then
        -- P1-B: line-ups exist only for confirmed matches, so only a
        -- reschedule has selected players to tell.
        perform public.notification_lineup_fanout(
                  new, 'match_rescheduled', 'match:' || new.id || ':schedule:' || old.proposal_version,
                  jsonb_build_object('starts_at', new.starts_at, 'venue_name', new.venue_name, 'city', new.city,
                                     'previous_starts_at', old.starts_at));
      end if;
    else
      perform public.notification_add(
                v_owner, 'club_owner', 'schedule_declined',
                'match:' || new.id || ':proposal:' || old.proposal_version || ':declined',
                jsonb_build_object('opponent_name', v_opp, 'starts_at', old.proposed_starts_at,
                                   'venue_name', old.proposed_venue_name, 'reschedule', old.status = 'confirmed'),
                v_club, new.id);
    end if;
  end if;
  return null;
end;
$$;

create trigger matches_notify
  after update on public.matches
  for each row execute function public.matches_notify();

-- Line-ups: save_match_lineup deletes and re-inserts the players, so this
-- runs once per changed row AT COMMIT (deferred) and compares the player's
-- final selection with the one they were last told about.
create or replace function public.match_lineup_players_notify()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_match_id  uuid := coalesce(new.match_id, old.match_id);
  v_club_id   uuid := coalesce(new.club_id, old.club_id);
  v_member_id uuid := coalesce(new.member_id, old.member_id);
  v_member    public.club_members;
  v_match     public.matches;
  v_lineup    public.match_lineups;
  v_now       text;
  v_prev      text;
  v_type      text;
begin
  select * into v_member from public.club_members m where m.id = v_member_id;
  if not found then
    return null; -- account deleted: the state row went with the member
  end if;
  if v_member.status <> 'active' then
    -- Removed from the club (told by removed_from_club): forget the state,
    -- so a later re-selection is news again.
    delete from public.notification_lineup_state s where s.match_id = v_match_id and s.member_id = v_member_id;
    return null;
  end if;
  select * into v_match from public.matches m where m.id = v_match_id;
  if not found or v_match.status <> 'confirmed' then
    return null;
  end if;
  select lp.selection into v_now from public.match_lineup_players lp
   where lp.match_id = v_match_id and lp.club_id = v_club_id and lp.member_id = v_member_id;
  select s.selection into v_prev from public.notification_lineup_state s
   where s.match_id = v_match_id and s.member_id = v_member_id
     for update;
  if v_now is not distinct from v_prev then
    return null;
  end if;
  if v_now is null then
    delete from public.notification_lineup_state s where s.match_id = v_match_id and s.member_id = v_member_id;
    v_type := 'lineup_dropped';
  else
    insert into public.notification_lineup_state (match_id, member_id, selection)
    values (v_match_id, v_member_id, v_now)
    on conflict (match_id, member_id) do update set selection = excluded.selection;
    v_type := case when v_prev is null then 'lineup_selected' else 'lineup_changed' end;
  end if;
  select * into v_lineup from public.match_lineups l where l.match_id = v_match_id and l.club_id = v_club_id;
  perform public.notification_add(
            v_member.user_id, case when v_member.member_role = 'owner' then 'club_owner' else 'player' end, v_type,
            'lineup:' || v_match_id || ':' || v_member_id || ':' || txid_current() || ':' || coalesce(v_now, 'dropped'),
            jsonb_build_object(
              'club_name', (select c.name from public.clubs c where c.id = v_club_id),
              'opponent_name', (select c.name from public.clubs c
                                 where c.id = case when v_club_id = v_match.club_a_id then v_match.club_b_id
                                                   else v_match.club_a_id end),
              'starts_at', v_match.starts_at, 'venue_name', v_match.venue_name,
              'selection', v_now, 'previous_selection', v_prev,
              'leader', case when v_now = 'playing' and v_lineup.captain_member_id = v_member_id then 'captain'
                             when v_now = 'playing' and v_lineup.vice_captain_member_id = v_member_id then 'vice_captain' end),
            v_club_id, v_match_id);
  return null;
end;
$$;

