-- ---------------------------------------------------------------------------
-- 2. A notification never changes, except: read once; club / match / person
--    links cleared by their foreign keys — and then the person's name goes.
-- ---------------------------------------------------------------------------
create or replace function public.notifications_guard_update()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_forget boolean := old.person_id is not null and new.person_id is null;
begin
  if v_forget then
    new.params := (new.params - 'person_name') || jsonb_build_object('person_deleted', true);
  end if;
  if (to_jsonb(new) - array['read_at', 'club_id', 'match_id', 'person_id', 'params'])
       is distinct from (to_jsonb(old) - array['read_at', 'club_id', 'match_id', 'person_id', 'params'])
     or (new.read_at is distinct from old.read_at and (old.read_at is not null or new.read_at is null))
     or (new.club_id is not null and new.club_id is distinct from old.club_id)
     or (new.match_id is not null and new.match_id is distinct from old.match_id)
     or (new.person_id is not null and new.person_id is distinct from old.person_id)
     or (not v_forget and new.params is distinct from old.params) then
    raise exception 'notification: invalid change' using errcode = '23514';
  end if;
  return new;
end;
$$;

create trigger notifications_guard_update
  before update on public.notifications
  for each row execute function public.notifications_guard_update();

