-- CricEco · migration 5 · public.clubs — a Club Owner's own club (additive only)
-- Stage 2: permanent club storage (was in memory, D6).
--
-- Adds, and changes nothing that exists (no existing table, column, policy,
-- grant or row is touched):
--   * public.clubs — one club per owner (profiles.id), RLS own-row
--   * clubs_assign_code()  — database-generated unique 6-character join code
--   * clubs_validate()     — the owner's User Profile Setup must be complete
--   * clubs_set_owner_role() — profiles.role becomes club_owner (over player,
--                             never downgraded: D-C1), in the same transaction
--   * create_club()        — Create Club in one transaction, safe to retry
-- The triggers apply to every insert, so the rules hold whichever way a club
-- row is written; create_club() is the path the app uses.
--
-- Depends on migrations 1–2: public.set_last_updated_at(), profiles.role,
-- profiles.profile_completed / date_of_birth and the two address tables.
-- Deliberately not here (approved Stage 2 decisions): the club logo stays on
-- the device; members, teams and join requests stay in the app's memory;
-- other users can't look a club up by its code yet (no cross-owner read).
--
-- NOT APPLIED. Run tests/00d_preflight_clubs.sql first (see supabase/README.md).

-- ---------------------------------------------------------------------------
-- Table. Text limits match the app's Club Setup / Club profile forms.
-- ---------------------------------------------------------------------------
create table public.clubs (
  id               uuid primary key default gen_random_uuid(),
  owner_id         uuid not null
                   constraint clubs_owner_id_key unique
                   references public.profiles (id) on delete cascade,
  -- Not only digits / spaces / punctuation ("123", "--" are refused). The app
  -- requires a Unicode letter; this form is never stricter than the app,
  -- whatever the database locale (an Urdu name always passes).
  name             text not null
                   constraint clubs_name_check
                   check (char_length(btrim(name)) between 1 and 100
                          and btrim(name) !~ '^[[:digit:][:space:][:punct:]]+$'),
  short_name       text
                   constraint clubs_short_name_check
                   check (short_name is null or char_length(btrim(short_name)) between 1 and 40),
  city             text not null
                   constraint clubs_city_check
                   check (char_length(btrim(city)) between 1 and 100),
  club_type        text not null
                   constraint clubs_club_type_check
                   check (club_type in ('professional', 'college_university', 'corporate')),
  -- Set by clubs_assign_code() on insert; never writable by the app.
  code             text not null
                   constraint clubs_code_key unique
                   constraint clubs_code_check check (code ~ '^[A-Z0-9]{6}$'),
  owner_name       text
                   constraint clubs_owner_name_check
                   check (owner_name is null or char_length(btrim(owner_name)) between 2 and 100),
  address          text
                   constraint clubs_address_check
                   check (address is null or char_length(btrim(address)) between 1 and 500),
  email            text
                   constraint clubs_email_check
                   check (email is null or (char_length(email) <= 254 and email ~ '^[^\s@]+@[^\s@]+\.[^\s@]{2,}$')),
  -- A ground id from the app's grounds list (no grounds table yet).
  home_ground_id   text
                   constraint clubs_home_ground_id_check
                   check (home_ground_id is null or char_length(home_ground_id) between 1 and 64),
  established_year smallint
                   constraint clubs_established_year_check
                   check (established_year is null or established_year between 1800 and 2100),
  created_at       timestamptz not null default now(),
  last_updated_at  timestamptz not null default now()
);

comment on table public.clubs is
  'A Club Owner''s own club (one per owner). Members, teams and join requests are not stored here yet.';
comment on column public.clubs.code is
  'Join code: 6 characters, generated by the database (clubs_assign_code), unique.';

-- ---------------------------------------------------------------------------
-- Join code. Always generated here (a value sent by the client is replaced).
-- 32-letter alphabet without 0/O/1/I; one random byte per character from
-- gen_random_uuid() (256 = 8 × 32, so every letter is equally likely).
-- SECURITY DEFINER only so the uniqueness check sees every club (RLS shows a
-- caller only their own); it reads codes and nothing else. The unique
-- constraint still guards the (≈1 in 10⁹) concurrent-collision case.
-- ---------------------------------------------------------------------------
create or replace function public.clubs_assign_code()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  alphabet  constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  bytes     bytea;
  candidate text;
begin
  loop
    bytes := uuid_send(gen_random_uuid());
    candidate := '';
    for i in 0..5 loop
      candidate := candidate || substr(alphabet, 1 + (get_byte(bytes, i) % 32), 1);
    end loop;
    exit when not exists (select 1 from public.clubs where code = candidate);
  end loop;
  new.code := candidate;
  return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- A club needs its owner's User Profile Setup done — the same definition as
-- the app: profile_completed, a date of birth and both addresses. Runs as the
-- caller, so RLS limits the lookup to their own rows. The message reuses the
-- profiles wording the app already turns into "Please complete all profile
-- details".
-- ---------------------------------------------------------------------------
create or replace function public.clubs_validate()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if not exists (
       select 1 from public.profiles p
        where p.id = new.owner_id and p.profile_completed is true and p.date_of_birth is not null)
     or not exists (select 1 from public.current_addresses where user_id = new.owner_id)
     or not exists (select 1 from public.permanent_addresses where user_id = new.owner_id) then
    raise exception 'profile_completed requires a completed User Profile Setup before creating a club'
      using errcode = '23514';
  end if;
  return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- Owning a club makes profiles.role club_owner: over player, never
-- downgraded (D-C1). Same transaction as the insert. Runs as the caller
-- (own-row profiles UPDATE policy); the inserted row's owner is the caller.
-- ---------------------------------------------------------------------------
create or replace function public.clubs_set_owner_role()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  update public.profiles
     set role = 'club_owner'
   where id = new.owner_id
     and (role is null or role = 'player');
  return null;
end;
$$;

-- Trigger functions (RETURNS trigger) can't be called directly, so they
-- aren't callable through the API.
create trigger clubs_assign_code
  before insert on public.clubs
  for each row execute function public.clubs_assign_code();

create trigger clubs_validate
  before insert on public.clubs
  for each row execute function public.clubs_validate();

create trigger clubs_set_owner_role
  after insert on public.clubs
  for each row execute function public.clubs_set_owner_role();

-- created_at can't change; last_updated_at follows every update (migration 1).
create trigger clubs_set_last_updated_at
  before update on public.clubs
  for each row execute function public.set_last_updated_at();

-- ---------------------------------------------------------------------------
-- Row Level Security: own club only. No DELETE policy (the club goes with
-- its owner's profile: ON DELETE CASCADE).
-- ---------------------------------------------------------------------------
alter table public.clubs enable row level security;

create policy "clubs: select own"
  on public.clubs for select to authenticated
  using ((select auth.uid()) = owner_id);
create policy "clubs: insert own"
  on public.clubs for insert to authenticated
  with check ((select auth.uid()) = owner_id);
create policy "clubs: update own"
  on public.clubs for update to authenticated
  using ((select auth.uid()) = owner_id)
  with check ((select auth.uid()) = owner_id);

-- Least privilege. Nothing for anon. Signed-in users may write only the
-- editable columns: id, owner_id (after insert), code and the timestamps
-- can't be set or changed from the app.
revoke all on table public.clubs from anon, authenticated;
grant select on table public.clubs to authenticated;
grant insert (owner_id, name, short_name, city, club_type, owner_name, address,
              email, home_ground_id, established_year)
  on table public.clubs to authenticated;
grant update (name, short_name, city, club_type, owner_name, address,
              email, home_ground_id, established_year)
  on table public.clubs to authenticated;

-- ---------------------------------------------------------------------------
-- Create Club in one transaction: the club row, its join code and
-- profiles.role (triggers above). SECURITY INVOKER: everything runs as the
-- caller under RLS, for auth.uid() only. Retrying returns the existing club
-- unchanged (one club per owner). Blank optional values are stored as NULL;
-- the established year starts as the current year.
-- ---------------------------------------------------------------------------
create or replace function public.create_club(
  p_name           text,
  p_city           text,
  p_club_type      text,
  p_owner_name     text default null,
  p_address        text default null,
  p_email          text default null,
  p_home_ground_id text default null
)
returns public.clubs
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_uid  uuid := auth.uid();
  v_club public.clubs;
begin
  if v_uid is null then
    raise exception 'not authenticated' using errcode = '42501';
  end if;
  if nullif(btrim(p_name), '') is null then
    raise exception 'club name is required' using errcode = '23514';
  end if;
  if nullif(btrim(p_city), '') is null then
    raise exception 'club city is required' using errcode = '23514';
  end if;
  if nullif(btrim(p_club_type), '') is null then
    raise exception 'club type is required' using errcode = '23514';
  end if;

  insert into public.clubs (owner_id, name, city, club_type, owner_name, address,
                            email, home_ground_id, established_year)
  values (v_uid, btrim(p_name), btrim(p_city), btrim(p_club_type),
          nullif(btrim(p_owner_name), ''), nullif(btrim(p_address), ''),
          nullif(btrim(p_email), ''), nullif(btrim(p_home_ground_id), ''),
          extract(year from now())::smallint)
  on conflict (owner_id) do nothing;

  select * into strict v_club from public.clubs where owner_id = v_uid;
  return v_club;
end;
$$;

revoke execute on function public.create_club(text, text, text, text, text, text, text) from public, anon;
grant execute on function public.create_club(text, text, text, text, text, text, text) to authenticated;
